# Session 3 - Asking Questions

score = 150

print("Your score is", score)


# "if" asks a question. The indented lines below only run
# when the answer is yes.
if score > 100:
    print("  That is a high score!")
    print("  Well done.")

print("This line is NOT indented, so it always runs.")


print()

lives = 0

# "else" is what happens when the answer is no.
if lives > 0:
    print("You still have lives left.")
else:
    print("Game over.")
